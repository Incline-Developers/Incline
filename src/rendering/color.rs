pub(crate) fn hex_to_linear_rgba(c: u32) -> [f32; 4] {
    [
        byte_to_linear_rgba(((c >> 16) & 0xff) as u8),
        byte_to_linear_rgba(((c >> 8) & 0xff) as u8),
        byte_to_linear_rgba((c & 0xff) as u8),
        1.0,
    ]
}

/// Convert an AutoCAD Color Index (1..=255) to a linear RGBA colour.
/// Returns `None` for 0 (ByBlock) and out-of-range values.
pub(crate) fn aci_to_linear_rgba(aci: i32) -> Option<[f32; 4]> {
    if aci <= 0 || aci >= 256 {
        return None;
    }
    let rgb = COLOR_TABLE[aci as usize];
    Some([byte_to_linear_rgba(rgb[0]), byte_to_linear_rgba(rgb[1]), byte_to_linear_rgba(rgb[2]), 1.0])
}

/// Convert an 8-bit `[R, G, B]` triple (sRGB) to linear RGBA with full alpha.
pub(crate) fn rgb_bytes_to_linear_rgba(rgb: [u8; 3]) -> [f32; 4] {
    hex_to_linear_rgba(((rgb[0] as u32) << 16) | ((rgb[1] as u32) << 8) | rgb[2] as u32)
}

pub(crate) fn byte_to_linear_rgba(c: u8) -> f32 {
    let x = c as f32 / 255.0;
    if x > 0.04045 { ((x + 0.055) / 1.055).powf(2.4) } else { x / 12.92 }
}

pub(crate) fn linear_to_srgb(linear: f32) -> f32 {
    let x = linear.clamp(0.0, 1.0);
    if x > 0.0031308 { 1.055 * x.powf(1.0 / 2.4) - 0.055 } else { 12.92 * x }
}

pub(crate) fn linear_to_srgb_byte(linear: f32) -> u8 {
    let srgb = linear_to_srgb(linear);
    (srgb * 255.0).round().clamp(0.0, 255.0) as u8
}

pub(crate) fn rgba_to_color32(rgba: [f32; 4]) -> egui::Color32 {
    egui::Color32::from_rgba_unmultiplied(
        linear_to_srgb_byte(rgba[0]),
        linear_to_srgb_byte(rgba[1]),
        linear_to_srgb_byte(rgba[2]),
        (rgba[3].clamp(0.0, 1.0) * 255.0).round() as u8,
    )
}

pub(crate) fn color32_to_rgba(c: egui::Color32) -> [f32; 4] {
    let (r, g, b, a) = c.to_srgba_unmultiplied().into();
    [byte_to_linear_rgba(r), byte_to_linear_rgba(g), byte_to_linear_rgba(b), a as f32 / 255.0]
}
